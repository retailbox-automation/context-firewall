import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATEGORIES, detect, resolveOverlaps } from '../core/detect.ts';
import type { Category } from '../core/detect.ts';
import { GENRES, generate } from './gen.ts';
import type { Corpus, Genre } from './gen.ts';

export interface CatStats {
  truth: number;
  found: number;
  tp: number;
  fp: number;
  recall: number;
  precision: number;
}

export interface EvalResult {
  seed: number;
  size: number;
  version: string;
  categories: Record<string, CatStats>;
  /** share of truth spans covered by a finding of any category */
  anyCategoryRecall: number;
  byGenre: Record<string, { truth: number; recall: number }>;
}

const ratio = (a: number, b: number): number => (b === 0 ? 1 : Math.round((a / b) * 10000) / 10000);
const overlaps = (a: { start: number; end: number }, b: { start: number; end: number }): boolean => a.start < b.end && b.start < a.end;

export function evaluate(corpus: Corpus, seed: number, version: string): EvalResult {
  const hashes = new Set(corpus.knownHashes);
  const acc = Object.fromEntries(CATEGORIES.map((c) => [c, { truth: 0, found: 0, tp: 0, fp: 0 }])) as Record<Category, { truth: number; found: number; tp: number; fp: number }>;
  const genre = Object.fromEntries(GENRES.map((g) => [g, { truth: 0, hit: 0 }])) as Record<Genre, { truth: number; hit: number }>;
  let anyHit = 0;
  let truthTotal = 0;
  for (const doc of corpus.docs) {
    const found = resolveOverlaps(detect(doc.text, { knownHashes: hashes }));
    for (const t of doc.truth) {
      const a = acc[t.category];
      a.truth++;
      truthTotal++;
      genre[doc.genre].truth++;
      if (found.some((f) => f.category === t.category && overlaps(f, t))) a.tp++;
      if (found.some((f) => overlaps(f, t))) {
        anyHit++;
        genre[doc.genre].hit++;
      }
    }
    for (const f of found) {
      const a = acc[f.category];
      a.found++;
      if (!doc.truth.some((t) => t.category === f.category && overlaps(f, t))) a.fp++;
    }
  }
  const categories: Record<string, CatStats> = {};
  for (const c of CATEGORIES) {
    const a = acc[c];
    categories[c] = { truth: a.truth, found: a.found, tp: a.tp, fp: a.fp, recall: ratio(a.tp, a.truth), precision: ratio(a.found - a.fp, a.found) };
  }
  return {
    seed,
    size: corpus.docs.length,
    version,
    categories,
    anyCategoryRecall: ratio(anyHit, truthTotal),
    byGenre: Object.fromEntries(GENRES.map((g) => [g, { truth: genre[g].truth, recall: ratio(genre[g].hit, genre[g].truth) }])),
  };
}

const pct = (x: number): string => (x * 100).toFixed(1) + '%';

export function table(res: EvalResult): string {
  const rows = ['| category | truth | found | recall | precision |', '|---|---:|---:|---:|---:|'];
  for (const [c, s] of Object.entries(res.categories)) rows.push(`| ${c} | ${s.truth} | ${s.found} | ${pct(s.recall)} | ${pct(s.precision)} |`);
  return rows.join('\n');
}

function markdown(res: EvalResult): string {
  const genres = Object.entries(res.byGenre).map(([g, s]) => `| ${g} | ${s.truth} | ${pct(s.recall)} |`).join('\n');
  return `# Eval: rules-only mode (\`--local\`)

Version ${res.version}, seed ${res.seed}, ${res.size} synthetic documents (payment-page text, email, OCR-style text with noise).
Every document carries all ${CATEGORIES.length} categories, written in several forms (PEM keys plain, JSON-escaped, legacy-encrypted and quoted; AWS secrets in .env form; card numbers with spaces, dashes, NBSP, dots and fullwidth digits), plus 12 to 18 hard negatives drawn from 45 kinds: Luhn-valid IMEIs and order numbers, unknown-IIN numbers, tax-id and IBAN look-alikes, key-shaped words and documentation placeholders, JWT-shaped blobs, public keys, and \`code\` words that are not logins. Several of them trip the detectors on purpose.
The generator does not import detector code. Three of the card numbers belong to networks outside the detector's list (Diners, Maestro) and count as misses.
The corpus is regenerated by \`npm run eval\` and is not committed.

A truth span counts as found when a finding of the same category overlaps it. A finding is a false positive when no truth span of its category overlaps it.

${table(res)}

Share of truth spans covered by a finding of any category: ${pct(res.anyCategoryRecall)}.

| genre | truth spans | covered (any category) |
|---|---:|---:|
${genres}

Limits: the corpus is synthetic and written by the same team as the detectors, so real pages will score lower. Noise is limited to doubled separators, glued labels and character swaps outside the secret; digits changed inside a secret are not covered. SSN, EIN, OTP and \`sk-\` rules are shape-based: an order number, part number or "code" word of the same shape is reported, which is where the low precision comes from. The card rule needs a known IIN (Visa, Mastercard, Amex, Discover, JCB, UnionPay).
`;
}

function arg(name: string, fallback: number): number {
  const i = process.argv.indexOf(`--${name}`);
  if (i < 0) return fallback;
  const n = Number(process.argv[i + 1]);
  if (!Number.isInteger(n) || n < 1) throw new RangeError(`--${name} needs a positive integer`);
  return n;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
  const version = (JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as { version: string }).version;
  const seed = arg('seed', 20261109);
  const count = arg('count', 300);
  const res = evaluate(generate({ seed, count }), seed, version);
  mkdirSync(join(root, 'docs'), { recursive: true });
  writeFileSync(join(root, 'docs', 'eval.json'), JSON.stringify(res, null, 2) + '\n');
  writeFileSync(join(root, 'docs', 'EVAL.md'), markdown(res));
  console.log(`eval: seed ${seed}, ${res.size} documents, version ${version}\n`);
  console.log(table(res));
  console.log(`\nany-category recall: ${pct(res.anyCategoryRecall)}`);
}
